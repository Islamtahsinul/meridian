"""Regenerate docs/SOURCES.md and .env.example from what the modules declare.

    python tools/gen_docs.py

Loads every module the way the server does (no network, no background work) and writes:
- docs/SOURCES.md: every data source with its licence/terms, refresh and layer;
- .env.example: every key and setting a module reads, with its description (values blank).

The app is built on a throwaway temporary data folder (deleted afterwards), so this never opens the live
data/meridian.db or writes the live server's log, whatever MERIDIAN_DATA_DIR says.
"""

from __future__ import annotations

import logging
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from server import build_app  # noqa: E402
from meridian.config import Config  # noqa: E402


def _close_logging() -> None:
    root = logging.getLogger("meridian")
    for handler in list(root.handlers):
        root.removeHandler(handler)
        try:
            handler.close()
        except Exception:
            pass


def main(out_dir: Path | None = None) -> int:
    out = Path(out_dir) if out_dir else ROOT
    scratch = tempfile.mkdtemp(prefix="meridian-gendocs-")
    app = None
    try:
        app = build_app(Config(None, overrides={"MERIDIAN_DATA_DIR": scratch}), console=False,
                        level=logging.WARNING)
        return _write(app, out)
    finally:
        if app is not None:
            try:
                app.store.close()
            except Exception:
                pass
        _close_logging()
        shutil.rmtree(scratch, ignore_errors=True)


def _write(app, out: Path) -> int:
    sources = sorted(app.sources.values(), key=lambda s: (s.get("module") or "", s.get("name") or s["id"]))
    lines = ["# Data sources", "",
             "Generated by `python tools/gen_docs.py` from what each module declares. Every source is public;",
             "Meridian uses them for personal, non-commercial use within their terms and credits them in the app",
             "(layer details, cards and Sources and status). Sources marked optional are off, need a key, or are",
             "often unreachable; the app works without them.", ""]
    current = None
    for s in sources:
        if s.get("module") != current:
            current = s.get("module")
            lines += ["", f"## {current}", "", "| Source | Licence or terms | Refresh | Layer |", "|---|---|---|---|"]
        name = s.get("name") or s["id"]
        url = s.get("url")
        label = f"[{name}]({url})" if url else name
        extra = []
        if s.get("needs_key"):
            extra.append(f"needs `{s['needs_key']}`")
        if s.get("optional"):
            extra.append("optional")
        if extra:
            label += f" ({', '.join(extra)})"
        cell = lambda v: str(v or "").replace("|", "/").replace("\n", " ")
        lines.append(f"| {cell(label)} | {cell(s.get('licence'))} | {cell(s.get('refresh'))} | {cell(s.get('layer'))} |")
    (out / "docs").mkdir(parents=True, exist_ok=True)
    (out / "docs" / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    env = ["# Meridian settings. Copy to .env (same folder as server.py) and fill in what you want.",
           "# Everything is optional: Meridian works with no keys at all, with less coverage.",
           "# Keys stay on this computer; the browser only learns whether each one is set.",
           "# Restart Meridian after editing.", "",
           "# Server (loopback only; any other host is refused)",
           "# MERIDIAN_HOST=127.0.0.1", "# MERIDIAN_PORT=8790", "# MERIDIAN_DATA_DIR=",
           "# Days of event history to keep (1 to 90)", "# MERIDIAN_HISTORY_DAYS=30", ""]
    current = None
    for k in sorted(app.config.declared.values(), key=lambda d: (d["module"], not d["secret"], d["name"])):
        if k["module"] != current:
            current = k["module"]
            env += ["", f"# ---- {current}"]
        desc = " ".join(str(k["description"]).split())
        env.append(f"# {desc}" + (f" ({k['url']})" if k.get("url") else ""))
        env.append(f"{k['name']}=" if k["secret"] else f"# {k['name']}=")
    (out / ".env.example").write_text("\n".join(env) + "\n", encoding="utf-8")
    print(f"wrote docs/SOURCES.md ({len(sources)} sources) and .env.example ({len(app.config.declared)} settings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
